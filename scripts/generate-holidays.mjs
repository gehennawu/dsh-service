/**
 * 生成 `src/holidays.generated.js`（入库）：中国法定节假日数据，供客户端峰谷时段判定使用。
 *
 * 与 `scripts/generate-model-icons.mjs` 同构的开发期生成物：**联网只发生在跑这个脚本时**，
 * 产物是纯数据字面量，由 `scripts/build-client.mjs` 构建期内联进 `client.js`。
 * 运行期零出网、零 RPC 端点、不接受任何浏览器输入——因此本方案不需要开 AGENTS.md 里
 * 「输入 URL 即出网」的例外通道；上游 URL 只活在本文件里，而 `scripts/` 不在
 * package.json 的 files 白名单内，根本不进 npm 包。
 *
 * 危险面在上游 JSON → 代码这一步的注入：**绝不回灌上游原始文本**。全部条目先解析、
 * 再逐条白名单校验、最后由本文件的序列化器重新生成字面量；任何畸形数据都让脚本报错退出，
 * 而不是把可疑内容随版本永久分发给用户。
 *
 * 用法：node scripts/generate-holidays.mjs
 */

import { writeFile } from 'node:fs/promises'
import { pathToFileURL } from 'node:url'

// 上游：中国法定节假日数据，自动每日抓取国务院公告（MIT）。
// 数据最终源自 gov.cn，本脚本只做转录搬运；README 的「注意事项」明确：年份按国务院文件
// 标题年份归档，12 月日期可能被下一年文件影响，故**必须同时检查相邻年份**。
const SOURCE_BASE = 'https://raw.githubusercontent.com/NateScarlet/holiday-cn/master'

/** 覆盖年份窗口：以当前北京年为中心，含次年（次年文件此时通常为空槽位，属正常状态）。 */
const BASE_YEAR = new Date(Date.now() + 8 * 3600 * 1000).getUTCFullYear()
const YEARS = [BASE_YEAR - 1, BASE_YEAR, BASE_YEAR + 1]

const DAY_RE = /^\d{4}-\d{2}-\d{2}$/
const MAX_DAYS_PER_YEAR = 400
const MAX_NAME_CHARS = 32
const FETCH_TIMEOUT_MS = 15000
const MAX_RESPONSE_BYTES = 256 * 1024

// 生成物只落**类别枚举**，不落任何展示文案：zh/en 文案在客户端 locale 词典里
// （`quota.holiday.<category>`），UI 只取 key。上游 name 是中文自由文本，直接渲染会
// 同时违反「en 界面不得出中文」与「文案走词典」两条客户端约束。
// 映射表是本仓库常量：上游改文案不影响我们，未命中归 other（无假期名可渲染，不阻断生成）。
const CATEGORY_RULES = [
  ['new-year', ['元旦']],
  ['spring-festival', ['春节']],
  ['qingming', ['清明']],
  ['labour-day', ['劳动节']],
  ['dragon-boat', ['端午']],
  ['mid-autumn', ['中秋']],
  ['national-day', ['国庆']],
]

/** 上游 name（可能形如「国庆节、中秋节」）→ 类别枚举；未命中归 other（无假期名可渲染，不阻断生成）。 */
export function categoryOf(name) {
  for (const [category, needles] of CATEGORY_RULES) {
    if (needles.some((needle) => name.includes(needle))) return category
  }
  return 'other'
}

async function fetchYear(year) {
  const url = `${SOURCE_BASE}/${year}.json`
  const controller = new AbortController()
  const timer = setTimeout(() => controller.abort(), FETCH_TIMEOUT_MS)
  try {
    const response = await fetch(url, { signal: controller.signal, redirect: 'error' })
    if (response.status !== 200) throw new Error(`${year}.json -> HTTP ${response.status}`)
    const text = await response.text()
    if (Buffer.byteLength(text, 'utf8') > MAX_RESPONSE_BYTES) throw new Error(`${year}.json exceeds ${MAX_RESPONSE_BYTES} bytes`)
    return JSON.parse(text)
  } finally {
    clearTimeout(timer)
  }
}

/**
 * 校验一份上游年份文件。返回 `{ paper, days }`：`days` 为该年 `isOffDay === true`
 * 的日期 → 类别。**`papers` 或 `days` 为空即判该年无数据**——上游会提前建好次年空槽位
 * （实测 `2027.json` 返回 200 且 `days: []`），把空数据当成「该年没有假期」会让
 * 客户端的降级提示永远不会触发，等于把「未知」伪装成「已知」。
 */
export function validateYear(year, payload) {
  if (payload === null || typeof payload !== 'object' || Array.isArray(payload)) {
    throw new Error(`${year}.json: root is not an object`)
  }
  if (payload.year !== year) throw new Error(`${year}.json: year field is ${JSON.stringify(payload.year)}, expected ${year}`)
  if (!Array.isArray(payload.papers) || payload.papers.length === 0) return { paper: null, days: new Map() }
  const paper = payload.papers.find((url) => typeof url === 'string' && url.startsWith('https://'))
  if (paper === undefined) throw new Error(`${year}.json: papers has no https entry`)
  if (!Array.isArray(payload.days)) throw new Error(`${year}.json: days is not an array`)
  const days = new Map()
  for (const entry of payload.days) {
    if (entry === null || typeof entry !== 'object' || Array.isArray(entry)) throw new Error(`${year}.json: day entry is not an object`)
    const { name, date, isOffDay } = entry
    if (typeof isOffDay !== 'boolean') throw new Error(`${year}.json: isOffDay is not a boolean`)
    if (typeof date !== 'string' || DAY_RE.test(date) === false) throw new Error(`${year}.json: invalid date ${JSON.stringify(date)}`)
    if (typeof name !== 'string' || name.trim() === '' || name.length > MAX_NAME_CHARS) throw new Error(`${year}.json: invalid name for ${date}`)
    // 只取放假日：days 里混有调休上班日（isOffDay:false），不得以「日期出现在 days 里」判假期。
    if (isOffDay !== true) continue
    if (days.has(date)) throw new Error(`${year}.json: duplicate off-day ${date}`)
    days.set(date, categoryOf(name))
  }
  if (days.size > MAX_DAYS_PER_YEAR) throw new Error(`${year}.json: ${days.size} off-days exceeds ${MAX_DAYS_PER_YEAR}`)
  return { paper, days }
}

/** 序列化：输出的每一个字节都由本函数产生，绝不拼接上游文本。 */
export function render(generated) {
  const lines = []
  lines.push('// AUTO-GENERATED by scripts/generate-holidays.mjs — do not edit manually.')
  lines.push(`// Source: NateScarlet/holiday-cn@master (MIT) · 中国法定节假日数据，转录自国务院办公厅通知。`)
  lines.push(`// Regenerate: node scripts/generate-holidays.mjs`)
  lines.push(`// 数据覆盖：${generated.years.join(' / ')}；未列出的年份视为「数据未覆盖」，客户端须降级提示而非按无假期处理。`)
  lines.push('const HOLIDAY_DATA = {')
  lines.push(`  years: ${JSON.stringify(generated.years)},`)
  lines.push(`  papers: ${JSON.stringify(generated.papers)},`)
  lines.push(`  offDays: ${JSON.stringify(generated.offDays)},`)
  lines.push('}')
  lines.push('')
  return lines.join('\n')
}

export async function main() {
  const years = []
  const papers = {}
  const offDays = {}

  for (const year of YEARS) {
    let payload
    try {
      payload = await fetchYear(year)
    } catch (error) {
      throw new Error(`failed to fetch ${year}: ${error.message}`)
    }
    const { paper, days } = validateYear(year, payload)
    if (paper === null || days.size === 0) {
      console.log(`${year}: 上游暂无安排（空槽位），不计入覆盖年份`)
      continue
    }
    years.push(year)
    papers[String(year)] = paper
    for (const [date, category] of days) offDays[date] = category
    console.log(`${year}: ${days.size} 个放假日 · ${paper}`)
  }

  if (years.length === 0) throw new Error('no year with holiday data was produced; refusing to write an empty dataset')

  await writeFile(new URL('../src/holidays.generated.js', import.meta.url), render({ years, papers, offDays }), 'utf8')
  console.log(`wrote src/holidays.generated.js (${Object.keys(offDays).length} off-days across ${years.join(', ')})`)
}

// 仅在直接执行时联网与写盘；被测试 import 时零副作用。
if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await main()
}
